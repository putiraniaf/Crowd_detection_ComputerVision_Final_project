def dual_pass_detect(detector, image, params_strong, params_weak):
    # Make copies so we can temporarily disable filtering inside detect()
    ps = params_strong.copy()
    pw = params_weak.copy()

    # Disable per-pass final filtering (keep everything after NMS)
    ps["min_final_score"] = -999
    pw["min_final_score"] = -999

    boxes_s, weights_s = detector.detect(image, ps)
    boxes_w, weights_w = detector.detect(image, pw)

    all_boxes = boxes_s + boxes_w
    all_weights = weights_s + weights_w

    # Final NMS
    final_boxes, final_weights = detector._improved_nms(all_boxes, all_weights, params_strong)

    final_min_score = params_weak.get("min_final_score", 0.35)
    clean_boxes, clean_weights = [], []
    for b, w in zip(final_boxes, final_weights):
        if w >= final_min_score:
            clean_boxes.append(b)
            clean_weights.append(w)

    return clean_boxes, clean_weights

def estimate_crowd_density(boxes, image_shape):
    h, w = image_shape[:2]
    image_area = w * h

    total_person_area = 0
    for (_, _, bw, bh) in boxes:
        total_person_area += bw * bh

    density_ratio = total_person_area / image_area

    # heuristic mapping
    if density_ratio < 0.02:
        level = "Low"
    elif density_ratio < 0.05:
        level = "Medium"
    elif density_ratio < 0.08:
        level = "High"
    else:
        level = "Very High"

    return density_ratio, level

