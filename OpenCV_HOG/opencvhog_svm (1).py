class ImprovedHOGDetector:
    def __init__(self):
        self.hog = cv2.HOGDescriptor()
        self.hog.setSVMDetector(cv2.HOGDescriptor_getDefaultPeopleDetector())

        self.base_width = 64
        self.base_height = 128
        self.aspect_ratio = self.base_width / self.base_height  # 0.5

    def detect(self, image, params):
        # 1) preprocessing
        if params.get("use_preprocessing", False):
            image = self._preprocess_image(
                image,
                params.get("brightness", 1.0),
                params.get("contrast", 1.0),
                params.get("sharpen", False),
            )

        # 2) multiscale proposals
        boxes, weights = self._detect_multiscale_improved(image, params)
        if len(boxes) == 0:
            return [], []

        # 3) geometry filtering
        boxes, weights = self._filter_boxes(boxes, weights, image.shape, params)
        if len(boxes) == 0:
            return [], []

        # 4) NMS
        boxes, weights = self._improved_nms(boxes, weights, params)
        if len(boxes) == 0:
            return [], []

        # 5) final score filtering
        min_final_score = params.get("min_final_score", 1.0)
        final_boxes, final_weights = [], []
        for b, w in zip(boxes, weights):
            if w >= min_final_score:
                final_boxes.append(b)
                final_weights.append(w)

        return final_boxes, final_weights



    def _detect_multiscale_improved(self, image, params):
        h, w = image.shape[:2]
        all_boxes, all_weights = [], []

        scales = self._calculate_smart_scales(image.shape, params)

        win_stride = params.get("win_stride", (4, 4))
        padding = params.get("padding", (8, 8))
        internal_scale = params.get("internal_scale", 1.10)
        hit_threshold = params.get("hit_threshold", 1.0)

        for scale in scales:
            scaled_h = int(h * scale)
            scaled_w = int(w * scale)

            if scaled_h < 128 or scaled_w < 64:
                continue

            scaled_img = cv2.resize(image, (scaled_w, scaled_h)) if scale != 1.0 else image

            try:
                boxes, weights = self.hog.detectMultiScale(
                    scaled_img,
                    winStride=win_stride,
                    padding=padding,
                    scale=internal_scale,
                    hitThreshold=hit_threshold,
                    useMeanshiftGrouping=False,
                )

                if len(boxes) > 0:
                    boxes = boxes.astype(np.float32)
                    boxes[:, :2] /= scale  # x,y
                    boxes[:, 2:] /= scale  # w,h

                    all_boxes.extend(boxes.tolist())
                    all_weights.extend(weights.flatten().tolist())

            except:
                continue

        return all_boxes, all_weights

    def _calculate_smart_scales(self, img_shape, params):
      min_person_h = params.get("min_person_px", 40)
      max_person_h = params.get("max_person_px", 260)

      # Correct direction:
      # small person -> big scale (upscale)
      # big person -> small scale (downscale)
      min_scale = self.base_height / max_person_h
      max_scale = self.base_height / min_person_h

      num_scales = params.get("num_scales", 10)
      scales = np.logspace(np.log10(min_scale), np.log10(max_scale), num=num_scales)

      # Optional: detect small people first (usually helps)
      scales = np.sort(scales)[::-1]

      return scales.tolist()


    def _filter_boxes(self, boxes, weights, img_shape, params):
        boxes = np.array(boxes, dtype=np.float32)
        weights = np.array(weights, dtype=np.float32)

        h, w = img_shape[:2]

        bw = boxes[:, 2]
        bh = boxes[:, 3]
        areas = bw * bh
        aspect = bw / (bh + 1e-6)

        min_area = params.get("min_box_area", 1200)
        max_area = params.get("max_box_area", None)
        if max_area is None:
            max_area = w * h * 0.30

        min_aspect = params.get("min_aspect_ratio", 0.35)
        max_aspect = params.get("max_aspect_ratio", 0.70)

        valid = (
            (areas >= min_area) &
            (areas <= max_area) &
            (aspect >= min_aspect) &
            (aspect <= max_aspect) &
            (boxes[:, 0] >= 0) &
            (boxes[:, 1] >= 0) &
            (boxes[:, 0] + boxes[:, 2] <= w) &
            (boxes[:, 1] + boxes[:, 3] <= h)
        )

        return boxes[valid].tolist(), weights[valid].tolist()

    def _improved_nms(self, boxes, weights, params):
        if len(boxes) == 0:
            return [], []

        boxes = np.array(boxes, dtype=np.float32)
        weights = np.array(weights, dtype=np.float32)

        x1 = boxes[:, 0]
        y1 = boxes[:, 1]
        x2 = boxes[:, 0] + boxes[:, 2]
        y2 = boxes[:, 1] + boxes[:, 3]
        areas = boxes[:, 2] * boxes[:, 3]

        aspect = boxes[:, 2] / (boxes[:, 3] + 1e-6)
        aspect_bonus = 1.0 - np.abs(aspect - self.aspect_ratio)
        adjusted = weights * (1.0 + 0.2 * aspect_bonus)

        order = np.argsort(adjusted)[::-1]
        keep = []
        thr = params.get("nms_threshold", 0.12)

        while len(order) > 0:
            i = order[0]
            keep.append(i)
            if len(order) == 1:
                break

            xx1 = np.maximum(x1[i], x1[order[1:]])
            yy1 = np.maximum(y1[i], y1[order[1:]])
            xx2 = np.minimum(x2[i], x2[order[1:]])
            yy2 = np.minimum(y2[i], y2[order[1:]])

            w_ov = np.maximum(0, xx2 - xx1)
            h_ov = np.maximum(0, yy2 - yy1)
            inter = w_ov * h_ov

            union = areas[i] + areas[order[1:]] - inter
            iou = inter / (union + 1e-6)

            order = order[1:][iou <= thr]

        return boxes[keep].tolist(), weights[keep].tolist()

    def _preprocess_image(self, image, brightness, contrast, sharpen):
        processed = image.copy()

        if brightness != 1.0 or contrast != 1.0:
            processed = cv2.convertScaleAbs(
                processed, alpha=contrast, beta=(brightness - 1.0) * 50
            )

        if sharpen:
            kernel = np.array([[-1,-1,-1], [-1,9,-1], [-1,-1,-1]])
            processed = cv2.filter2D(processed, -1, kernel)

        return processed

    def _detect_pipeline(self, image, params):
        all_boxes, all_weights = self._detect_multiscale_improved(image, params)

        if len(all_boxes) == 0:
          return [], []

        filtered_boxes, filtered_weights = self._filter_boxes(
            all_boxes, all_weights, image.shape, params
        )

        if len(filtered_boxes) == 0:
            return [], []

        nms_boxes, nms_weights = self._improved_nms(
            filtered_boxes, filtered_weights, params
        )

        return nms_boxes, nms_weights

    def visualize(self, image, boxes, weights):
        result = image.copy()

        # Draw boxes with color based on confidence
        for i, (box, weight) in enumerate(zip(boxes, weights)):
            x, y, w, h = [int(v) for v in box]

            # Color based on confidence (green = high, yellow = medium, red = low)
            if weight > 1.5:
                color = (0, 255, 0)  # Green
            elif weight > 0.8:
                color = (0, 255, 255)  # Yellow
            else:
                color = (0, 165, 255)  # Orange

            cv2.rectangle(result, (x, y), (x + w, y + h), color, 2)

            # Label with confidence
            label = f"{weight:.2f}"
            label_size, _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 0.5, 1)
            cv2.rectangle(
                result, (x, y - label_size[1] - 4), (x + label_size[0], y), color, -1
            )
            cv2.putText(
                result, label, (x, y - 2), cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 0, 0), 1
            )

        # Statistics overlay
        num_people = len(boxes)
        h, w = image.shape[:2]
        density = num_people / ((w * h) / 1_000_000)

        if density < 5:
            crowd_level = "Low"
            level_color = (0, 255, 0)
        elif density < 15:
            crowd_level = "Medium"
            level_color = (0, 255, 255)
        elif density < 30:
            crowd_level = "High"
            level_color = (0, 165, 255)
        else:
            crowd_level = "Very High"
            level_color = (0, 0, 255)

        cv2.putText(
            result,
            f"People: {num_people}",
            (15, 30),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.8,
            (255, 255, 255),
            2,
        )
        cv2.putText(
            result,
            f"Crowd: {crowd_level}",
            (15, 60),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.8,
            level_color,
            2,
        )
        cv2.putText(
            result,
            f"Density: {density:.1f}/100k",
            (15, 90),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.8,
            (255, 255, 255),
            2,
        )

        return result

